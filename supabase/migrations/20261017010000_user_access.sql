-- User access list. Passwords are NOT stored here: Supabase Auth keeps them hashed in auth.users.
-- A row is "claimed" when someone signs up with a matching username; until then user_id is null.

create table if not exists public.user_access (
  id int generated by default as identity primary key,
  username text not null unique,
  user_id uuid unique references auth.users (id) on delete set null,
  role text not null default 'member' check (role in ('admin', 'member')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.user_access enable row level security;

create policy "own access row select" on public.user_access for select using (user_id = auth.uid());

-- User 1: Saurabh (admin). Claimed when Saurabh signs up with username "Saurabh".
insert into public.user_access (id, username, role)
values (1, 'Saurabh', 'admin')
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.user_access', 'id'), greatest((select max(id) from public.user_access), 1));

-- Signup: create the profile, then claim a matching unclaimed username or add a new access row.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  uname text := nullif(trim(new.raw_user_meta_data ->> 'username'), '');
begin
  insert into public.profiles (id, display_name) values (new.id, uname) on conflict do nothing;

  update public.user_access
     set user_id = new.id
   where user_id is null and lower(username) = lower(uname);

  if not found then
    insert into public.user_access (username, user_id)
    values (coalesce(uname, split_part(new.email, '@', 1)) || case
              when exists (select 1 from public.user_access where lower(username) = lower(coalesce(uname, split_part(new.email, '@', 1))))
              then '-' || left(new.id::text, 4) else '' end,
            new.id);
  end if;
  return new;
end;
$$;

-- Backfill users who signed up before this table existed.
insert into public.user_access (username, user_id)
select split_part(u.email, '@', 1) || '-' || left(u.id::text, 4), u.id
from auth.users u
where not exists (select 1 from public.user_access a where a.user_id = u.id);

notify pgrst, 'reload schema';
